import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";

// assayd.dev — the docs.
//
// Same constraint as the site: a plain static host, files pushed, no runtime.
// Starlight prerenders every page by default, which is what makes it usable
// here at all.
//
// No Mermaid, and no diagram-as-code integration of any kind. Every diagram on
// this target is a generated .webp plate placed with the shared Figure
// component. That is a decision, not an omission.
export default defineConfig({
  // Deliberately unset until DNS is pointed — see the note in the site config.

  output: "static",

  build: {
    // Starlight's own link formatter has an explicit branch for this: with
    // 'file' it appends .html and skips trailing-slash handling entirely.
    //
    // AUTHORING HAZARD, measured on Astro 7.3.3 + Starlight 0.42.2: Starlight
    // rewrites ITS OWN navigation under this setting, and does not rewrite
    // links written in page prose. Of five link spellings in a page body, all
    // five emitted verbatim, so only `/guides/example.html` resolved and
    // `/guides/example`, `/guides/example/`, `./guides/example.md` and
    // `./guides/example` did not. On a host with no rewrite rules a wrong link
    // is a hard 404, not a redirect.
    //
    // So: write every cross-reference with an explicit `.html`. That is
    // enforced — scripts/check-links.sh runs over the BUILT output in CI and
    // fails on it — and the enforcement was demonstrated by planting the bad
    // link and watching the gate go red while `astro build` stayed green.
    format: "file",
  },

  trailingSlash: "never",

  integrations: [
    starlight({
      title: "assayd docs",
      description:
        "Guides, reference and status for assayd, a Kubernetes-native agent platform.",
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/Quinyte/assayd",
        },
      ],
      // Ink + Gold. Loaded after Starlight's own sheet so the tokens win.
      //
      // base.css is here as well as tokens.css. Loading only the tokens meant
      // the shared reduced-motion reset, the .ax-sr-only utility and the
      // :focus-visible treatment reached the site target and not this one —
      // so "shared base" was not what shipped, which is the drift this
      // workspace exists to prevent. Starlight styles its own elements, and
      // base.css is deliberately thin, so the two coexist.
      customCss: [
        "@assayd/web-shared/tokens.css",
        "@assayd/web-shared/base.css",
        "./src/styles/starlight-ink-gold.css",
      ],
      // The sidebar is autogenerated from the directory tree so that the
      // agents who own the information architecture and the generated
      // reference can add pages without editing this file — and so that a page
      // added on disk cannot silently fail to appear in the navigation.
      sidebar: [
        // A single top-level page, named by slug: Starlight fails the build if
        // the slug has no page, so this entry cannot dangle.
        { slug: "what-runs-today" },
        {
          label: "Guides",
          items: [{ autogenerate: { directory: "guides" } }],
        },
        // Generated. The pages under reference/ are NOT in git here: they are
        // docs/reference/*.md, written by cmd/refgen and held to the code by
        // `make verify`, and web/scripts/copy-reference.sh copies them in before the
        // build so the link gate reads them. Edit the generator, never the copy.
        {
          label: "Reference",
          items: [{ autogenerate: { directory: "reference" } }],
        },
      ],
      // The generated CRD reference fences its x-kubernetes-validations as
      // ```cel, and Shiki bundles no CEL grammar, so each block warned and fell
      // back to plain text anyway. Aliasing to plain text says that on purpose
      // rather than as a warning: mapping CEL to a language it only resembles
      // would colour it by rules it does not follow.
      expressiveCode: {
        shiki: { langAlias: { cel: "txt" } },
      },
      pagination: false,
      credits: false,
    }),
  ],

  vite: {
    ssr: {
      noExternal: ["@assayd/web-shared"],
    },
  },
});
