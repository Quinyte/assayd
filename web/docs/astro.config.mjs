import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";

// assayd.dev — the docs.
//
// Same constraint as the site: a plain static host, files pushed, no runtime.
// Starlight prerenders every page by default, which is what makes it usable
// here at all.
//
// No Mermaid, and no diagram-as-code integration of any kind. Every diagram on
// this target is a generated .webp plate placed with the shared Figure
// component. That is a decision, not an omission.
export default defineConfig({
  // Deliberately unset until DNS is pointed — see the note in the site config.

  output: "static",

  build: {
    // Starlight's own link formatter has an explicit branch for this: with
    // 'file' it appends .html and skips trailing-slash handling entirely.
    //
    // AUTHORING HAZARD, measured on Astro 7.3.3 + Starlight 0.42.3: Starlight
    // rewrites ITS OWN navigation under this setting, and does not rewrite
    // links written in page prose. Of five link spellings in a page body, all
    // five emitted verbatim, so only `/guides/example.html` resolved and
    // `/guides/example`, `/guides/example/`, `./guides/example.md` and
    // `./guides/example` did not. On a host with no rewrite rules a wrong link
    // is a hard 404, not a redirect.
    //
    // So: write every cross-reference with an explicit `.html`. Nothing in
    // this repository enforces that yet — there is no link check in CI — which
    // is why it is written here as a hazard and not as a guarantee.
    format: "file",
  },

  trailingSlash: "never",

  integrations: [
    starlight({
      title: "assayd docs",
      description:
        "Guides, reference and status for assayd, a Kubernetes-native agent platform.",
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/Quinyte/assayd",
        },
      ],
      // Ink + Gold. Loaded after Starlight's own sheet so the tokens win.
      customCss: [
        "@assayd/web-shared/tokens.css",
        "./src/styles/starlight-ink-gold.css",
      ],
      // The sidebar is autogenerated from the directory tree so that the
      // agents who own the information architecture and the generated
      // reference can add pages without editing this file — and so that a page
      // added on disk cannot silently fail to appear in the navigation.
      sidebar: [
        {
          label: "Guides",
          items: [{ autogenerate: { directory: "guides" } }],
        },
      ],
      pagination: false,
      credits: false,
    }),
  ],

  vite: {
    ssr: {
      noExternal: ["@assayd/web-shared"],
    },
  },
});
